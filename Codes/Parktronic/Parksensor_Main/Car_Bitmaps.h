struct CarPiece {
  const uint8_t *rle;
  uint8_t w;
  uint8_t y0, h;
};

static const CarPiece CAR_PIECES[4] = {
  { PIECE_REAR_SIDE,  34, 0,   114 },
  { PIECE_REAR_MID,   21, 0,   114 },
  { PIECE_FRONT_SIDE, 34, 114, 122 },
  { PIECE_FRONT_MID,  21, 114, 122 },
};

static void drawCarPiece(Adafruit_GFX &d, const CarPiece &p, uint8_t xOff, bool mirror, uint16_t color) {
  const uint8_t *q = p.rle;
  for (uint8_t row = 0; row < p.h; ++row) {
    int16_t y = CAR_OFFSET_Y + (p.y0 + row) * CAR_S;
    uint8_t x = 0;
    bool black = false;
    while (x < p.w) {
      uint8_t n = pgm_read_byte(q++);
      if (black && n) {
        uint8_t px = mirror ? (xOff + p.w - x - n) : (xOff + x);
        d.writeFillRect(CAR_OFFSET_X + px * CAR_S, y, n * CAR_S, CAR_S, color);
      }
      x += n;
      black = !black;
    }
  }
}

// Zeichnet NUR die angegebene Zone (0..5).
static void drawCarZone(Adafruit_GFX &d, uint8_t zone, bool filled,
                        uint16_t fillColor, uint16_t lineColor, uint16_t bgColor) {
  if (zone > 5) return;
  bool front = zone < 3;
  uint8_t col = zone % 3;
  const CarPiece &side = CAR_PIECES[front ? 2 : 0];
  const CarPiece &mid  = CAR_PIECES[front ? 3 : 1];

  uint8_t zx0 = (col == 0) ? 0 : (col == 1) ? CAR_X1 : CAR_X2;
  uint8_t zx1 = (col == 0) ? CAR_X1 : (col == 1) ? CAR_X2 : CAR_WH;

  d.startWrite();
  d.writeFillRect(CAR_OFFSET_X + zx0 * CAR_S, CAR_OFFSET_Y + side.y0 * CAR_S,
                  (zx1 - zx0) * CAR_S, side.h * CAR_S, bgColor);
  if (filled) {
    for (uint8_t row = 0; row < side.h; ++row) {
      uint8_t y = side.y0 + row;
      uint8_t e = pgm_read_byte(&CAR_EDGE[y]);
      if (e == 255) continue;
      uint8_t s = (e > zx0) ? e : zx0;
      uint8_t t = CAR_WH - e;                 // exklusive rechte Kante
      if (t > zx1) t = zx1;
      if (t > s)
        d.writeFillRect(CAR_OFFSET_X + s * CAR_S, CAR_OFFSET_Y + y * CAR_S,
                        (t - s) * CAR_S, CAR_S, fillColor);
    }
  }
  if (col == 0)      drawCarPiece(d, side, 0, false, lineColor);
  else if (col == 2) drawCarPiece(d, side, CAR_WH - side.w, true, lineColor);
  else {
    drawCarPiece(d, mid, CAR_X1, false, lineColor);
    drawCarPiece(d, mid, CAR_X2 - mid.w, true, lineColor);
  }
  d.endWrite();
}

